@Injectable({ providedIn: 'root' })
export class SedesService {
  private http = inject(HttpClient);
  private base = `${environment.apiUrl}/sedes`;

  getAll(): Observable<Sede[]> {
    // return this.http.get<Sede[]>(this.base);
    return of(MOCK_SEDES).pipe(delay(300));
  }

  getById(id: number): Observable<Sede> {
    // return this.http.get<Sede>(`${this.base}/${id}`);
    return of(MOCK_SEDES.find(s => s.sedeId === id)!).pipe(delay(200));
  }

  getStats(): Observable<SedeStats> {
    const paises = new Set(MOCK_SEDES.map(s => s.pais)).size;
    const continentes = new Set(MOCK_SEDES.map(s => s.pais === 'Colombia' ? 'América del Sur' : 'América del Norte')).size;
    return of({
      totalSedes: MOCK_SEDES.length,
      totalMiembros: MOCK_SEDES.reduce((s, x) => s + x.totalMiembros, 0),
      totalPaises: paises,
      totalContinentes: continentes,
    }).pipe(delay(200));
  }
}
